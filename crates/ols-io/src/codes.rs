    /// The Swiss LeV plugin (when this checkout has it): its example
    /// generates load cases and the two clearance presets, each checked,
    /// solved by finite elements with the wind from both sides.
    #[test]
    fn lev_example_generates_clearance_presets() {
        let Some(dir) = lev_plugin() else {
            return;
        };
        let host = WasmHost::new().unwrap();
        let text = std::fs::read_to_string(dir.join("example-parameters.toml")).unwrap();
        let g = generate(&host, &dir, &text).unwrap();
        assert!(g.load_cases.cases.len() >= 2);
        let measures: Vec<Measure> = g.presets.iter().map(|p| p.measure).collect();
        assert_eq!(measures, [Measure::Vertical, Measure::Radial]);
        for p in &g.presets {
            let check = p.rules.check.as_ref().unwrap();
            assert_eq!(check.method, Some(ols_line::condition::Method::Fe));
            assert_eq!(check.search_distance, Some(30.0));
            assert_eq!(p.rules.wind.unwrap().sides, ols_clearance::WindSides::Both);
            assert_eq!(p.weather.cases.len(), 3, "{}", p.weather_text);
            assert!(!p.rules.rules.is_empty());
        }
    }

