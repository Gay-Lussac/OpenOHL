//! Design codes (`code-plugin` world, extension point `design-code`): a
//! plugin turns the user's parameter file into weather cases (`.olswc`)
//! and load cases (`.olslc`), checked here like any such file. OLS CAD
//! ships no code tables: every value of a code is in the parameter file.
//!
//! One generation is one plugin call (microseconds of arithmetic); the
//! plugin's own limits (ADR-0003, default 5 s) are its exit clause.

use std::path::{Path, PathBuf};

use ols_loads::LoadCases;
use ols_plugins::{Found, WasmHost};
use ols_weather::WeatherCases;

/// A design-code plugin found, for lists.
#[derive(Debug, Clone, PartialEq)]
pub struct CodePlugin {
    /// Its name.
    pub name: String,
    /// Its directory.
    pub dir: PathBuf,
    /// Version and description from its manifest.
    pub description: String,
    /// Why it cannot be used, if it cannot.
    pub problem: Option<String>,
}

impl From<&Found> for CodePlugin {
    fn from(f: &Found) -> Self {
        Self {
            name: f.name(),
            dir: f.dir.clone(),
            description: f.manifest.as_ref().map_or(String::new(), |m| {
                format!("{} — {}", m.plugin.version, m.plugin.description)
            }),
            problem: f.problem(),
        }
    }
}

/// The design-code plugins in `roots` (directories of plugins, or plugin
/// directories), in order; a name found again is left out.
pub fn list(roots: &[PathBuf]) -> Vec<CodePlugin> {
    ols_plugins::discover_codes(roots)
        .iter()
        .map(CodePlugin::from)
        .collect()
}

/// Weather cases and load cases generated by a design code, checked.
#[derive(Debug, Clone)]
pub struct Generated {
    /// The plugin's name.
    pub plugin: String,
    /// Weather case file text (`.olswc`).
    pub weather_text: String,
    /// Load case file text (`.olslc`).
    pub load_cases_text: String,
    /// The weather cases read.
    pub weather: WeatherCases,
    /// The load cases read.
    pub load_cases: LoadCases,
    /// The plugin's notes.
    pub notes: Vec<String>,
}

impl Generated {
    /// Reads and checks a plugin's output: both files read, every load
    /// case names one of the weather cases, neither file empty.
    pub fn check(
        plugin: &str,
        weather_text: String,
        load_cases_text: String,
        notes: Vec<String>,
    ) -> Result<Self, String> {
        let bad = |what: &str, e: String| format!("plugin {plugin} returned invalid {what}: {e}");
        let weather = WeatherCases::parse(&weather_text).map_err(|e| bad("weather cases", e))?;
        let load_cases = LoadCases::parse(&load_cases_text).map_err(|e| bad("load cases", e))?;
        if weather.cases.is_empty() || load_cases.cases.is_empty() {
            return Err(format!("plugin {plugin} generated no cases"));
        }
        for l in &load_cases.cases {
            if !weather.cases.iter().any(|w| w.name == l.weather) {
                return Err(bad(
                    "load cases",
                    format!("{}: no weather case \"{}\"", l.name, l.weather),
                ));
            }
        }
        Ok(Self {
            plugin: plugin.to_owned(),
            weather_text,
            load_cases_text,
            weather,
            load_cases,
            notes,
        })
    }

    /// Writes both files.
    pub fn write(&self, weather: &Path, load_cases: &Path) -> Result<(), String> {
        for (path, text) in [
            (weather, &self.weather_text),
            (load_cases, &self.load_cases_text),
        ] {
            if let Some(dir) = path.parent().filter(|d| !d.as_os_str().is_empty()) {
                std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
            }
            std::fs::write(path, text).map_err(|e| format!("{}: {e}", path.display()))?;
        }
        Ok(())
    }
}

/// The parameter file template of the design-code plugin in `dir`.
pub fn template(host: &WasmHost, dir: &Path) -> Result<String, String> {
    let mut plugin = host.load_code(dir).map_err(|e| e.to_string())?;
    Ok(plugin
        .describe()
        .map_err(|e| e.to_string())?
        .parameters_template)
}

/// Runs the design-code plugin in `dir` on a parameter file's text and
/// checks what it returns.
pub fn generate(host: &WasmHost, dir: &Path, parameters: &str) -> Result<Generated, String> {
    let mut plugin = host.load_code(dir).map_err(|e| e.to_string())?;
    let name = plugin.manifest().plugin.name.clone();
    let g = plugin
        .generate(parameters)
        .map_err(|e| e.to_string())?
        .map_err(|e| format!("plugin {name}: {e}"))?;
    Generated::check(&name, g.weather_cases, g.load_cases, g.notes)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn codes() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../plugins/codes")
    }

    /// The plugin in `plugins/codes/<name>` if built, `None` to skip.
    fn built(name: &str) -> Option<PathBuf> {
        let dir = codes().join(name);
        let m = ols_plugins::Manifest::load(&dir).unwrap();
        if m.entry_path().is_file() {
            return Some(dir);
        }
        assert!(
            std::env::var_os("OLS_REQUIRE_PLUGIN_TESTS").is_none(),
            "design-code plugin not built: {}",
            m.entry_path().display()
        );
        eprintln!("skipping: {name} not built");
        None
    }

    fn example(host: &WasmHost, name: &str) -> Option<Generated> {
        let dir = built(name)?;
        let text = std::fs::read_to_string(dir.join("example-parameters.toml")).unwrap();
        // One compilation: the template is the example file, which reads.
        let mut plugin = host.load_code(&dir).unwrap();
        assert_eq!(plugin.describe().unwrap().parameters_template, text);
        let g = plugin.generate(&text).unwrap().unwrap();
        Some(Generated::check(name, g.weather_cases, g.load_cases, g.notes).unwrap())
    }

    fn case<'a>(g: &'a Generated, name: &str) -> &'a ols_weather::WeatherCase {
        g.weather
            .cases
            .iter()
            .find(|c| c.name == name)
            .unwrap_or_else(|| panic!("no weather case {name}"))
    }

    fn load<'a>(g: &'a Generated, name: &str) -> &'a ols_loads::LoadCase {
        g.load_cases
            .cases
            .iter()
            .find(|c| c.name == name)
            .unwrap_or_else(|| panic!("no load case {name}"))
    }

    fn close(actual: f64, expected: f64) {
        assert!(
            (actual - expected).abs() <= 1e-6 * expected.abs().max(1.0),
            "{actual} ≠ {expected}"
        );
    }

    #[test]
    fn every_code_plugin_is_listed() {
        let found = list(&[codes()]);
        let names: Vec<&str> = found.iter().map(|c| c.name.as_str()).collect();
        assert_eq!(
            names,
            [
                "asce-mop74",
                "csa-c22-3",
                "en50341",
                "go95",
                "iec60826",
                "lev-ch",
                "nesc"
            ]
        );
        // A root that is a plugin directory lists itself; the same name
        // again is left out.
        assert_eq!(list(&[codes().join("nesc"), codes()]).len(), 7);
    }

    /// Every plugin's example parameters give cases that read; each
    /// plugin refuses a broken file with its own error.
    #[test]
    fn every_example_generates() {
        let host = WasmHost::new().unwrap();
        for c in list(&[codes()]) {
            let Some(g) = example(&host, &c.name) else {
                continue;
            };
            assert!(!g.weather.cases.is_empty(), "{}", c.name);
            assert!(g.load_cases.cases.len() >= 2, "{}", c.name);
            assert!(!g.notes.is_empty(), "{}", c.name);
            assert!(g.weather_text.contains("design-code plugin"), "{}", c.name);
            let e = generate(&host, &c.dir, "[project]\nname = 1").unwrap_err();
            assert!(e.contains(&format!("plugin {}", c.name)), "{e}");
        }
    }

    /// EN 50341: the NNA's basic wind velocity replaces the general one;
    /// q = c_e·½ρv_b²·G_c·C_c = 2.1 · ½·1.25·26² · 0.8 · 1.0 = 709.8 Pa;
    /// partial factors on the load cases, 1/γ_M as strength.
    #[test]
    fn en50341_example_by_hand() {
        let host = WasmHost::new().unwrap();
        let Some(g) = example(&host, "en50341") else {
            return;
        };
        let wind = case(&g, "EN extreme wind");
        close(wind.wind_pressure.pascals(), 709.8);
        close(wind.temperature.celsius(), 10.0);
        // With ice: (0.6 v_b)², C_c 1.1: 709.8 · 0.36 · 1.1.
        let iw = case(&g, "EN ice with wind");
        close(iw.wind_pressure.pascals(), 709.8 * 0.36 * 1.1);
        close(iw.ice_load.unwrap().newtons_per_meter(), 15.0);
        let lc = load(&g, "EN 3a ice dominant with wind");
        close(lc.vertical, 1.3);
        close(lc.transverse, 1.2 * 0.5);
        close(lc.strength, 1.0 / 1.1);
        // The NNA's own case.
        assert_eq!(load(&g, "NNA wet snow").weather, "NNA heavy wet snow");
        assert!(g.notes.iter().any(|n| n.contains("wind.basic_velocity")));
    }

    /// NESC: the heavy district's 4 psf (invented) in pascals; extreme
    /// wind 0.00256·k_z·G·C_f·V² psf.
    #[test]
    fn nesc_example_by_hand() {
        let host = WasmHost::new().unwrap();
        let Some(g) = example(&host, "nesc") else {
            return;
        };
        let psf = 4.448_221_615_260_5 / (0.3048 * 0.3048);
        let district = case(&g, "NESC district (heavy-example)");
        close(district.wind_pressure.pascals(), 3.5 * psf);
        close(district.ice_thickness.millimeters(), 0.4 * 25.4);
        close(district.temperature.celsius(), (5.0 - 32.0) / 1.8);
        let extreme = case(&g, "NESC extreme wind");
        close(
            extreme.wind_pressure.pascals(),
            0.00256 * 1.1 * 0.9 * 1.0 * 95.0 * 95.0 * psf,
        );
        let lc = load(&g, "NESC 250B district loading");
        close(lc.transverse, 2.2);
        close(lc.strength, 0.7);
    }

    /// Swiss LeV: the altitude zone's ice for the reference diameter,
    /// base + per-mm × d = 5 + 0.4 · 30 = 17 N/m (invented values).
    #[test]
    fn lev_example_by_hand() {
        let host = WasmHost::new().unwrap();
        let Some(g) = example(&host, "lev-ch") else {
            return;
        };
        let normal = case(&g, "LeV normal load (additional load)");
        close(normal.ice_load.unwrap().newtons_per_meter(), 17.0);
        close(case(&g, "LeV wind").wind_pressure.pascals(), 500.0);
        close(load(&g, "LeV normal load").strength, 1.0 / 2.5);
    }

    /// The other codes' first wind cases, by hand from their examples.
    #[test]
    fn other_examples_by_hand() {
        let host = WasmHost::new().unwrap();
        if let Some(g) = example(&host, "iec60826") {
            // ½·τ·μ·(K_R·V_R)² · C_xc · G_c · G_L
            let q0 = 0.5 * 1.0 * 1.225 * (1.0 * 30.0f64).powi(2);
            close(
                case(&g, "IEC wind").wind_pressure.pascals(),
                q0 * 1.0 * 1.9 * 0.95,
            );
        }
        if let Some(g) = example(&host, "asce-mop74") {
            // Q·k_z·K_zt·V²·G·C_f
            close(
                case(&g, "MOP 74 extreme wind").wind_pressure.pascals(),
                0.613 * 1.1 * 1.0 * 40.0 * 40.0 * 0.85 * 1.0,
            );
        }
        if let Some(g) = example(&host, "csa-c22-3") {
            close(
                case(&g, "CSA zone (heavy-example)")
                    .ice_thickness
                    .millimeters(),
                11.0,
            );
            close(load(&g, "CSA zone loading").vertical, 1.4);
        }
        if let Some(g) = example(&host, "go95") {
            // 1000 ft is above the 800 ft (invented) limit: the heavy
            // district.
            let psf = 4.448_221_615_260_5 / (0.3048 * 0.3048);
            close(
                case(&g, "GO 95 heavy-example loading")
                    .wind_pressure
                    .pascals(),
                5.0 * psf,
            );
            close(load(&g, "GO 95 at replacement").strength, 1.0 / 1.4);
        }
    }

    #[test]
    fn outputs_are_checked() {
        let w = "format = \"ols-weather-cases\"\nversion = 1\n[[case]]\nname = \"a\"\ntemperature = \"5 °C\"\n";
        let l = |weather: &str| {
            format!(
                "format = \"ols-load-cases\"\nversion = 1\n[[case]]\nname = \"x\"\nweather = \"{weather}\"\n"
            )
        };
        assert!(Generated::check("p", w.into(), l("a"), vec![]).is_ok());
        let e = Generated::check("p", w.into(), l("b"), vec![]).unwrap_err();
        assert!(e.contains("no weather case \"b\""), "{e}");
        assert!(Generated::check("p", "x = ".into(), l("a"), vec![]).is_err());
    }
}
